fn xs(seed: &mut u64) -> u64 {
    let mut x = *seed;
    x ^= x << 13;
    x ^= x >> 7;
    x ^= x << 17;
    *seed = x;
    x
}
fn text(out: &mut impl Write) -> io::Result<()> {
    let mut seed = 0x4c6f72644265;
    let mut written = 0;
    let mut line = 0;
    let mut cap = true;
    while written < CORPUS_SIZE {
        let mut word = WORDS[(xs(&mut seed) % WORDS.len() as u64) as usize]
            .as_bytes()
            .to_vec();
        if cap {
            word[0] = word[0].to_ascii_uppercase();
        }
        cap = false;
        match xs(&mut seed) % 23 {
            0 => {
                word.push(b'.');
                cap = true;
            }
            1 => word.push(b','),
            _ => {}
        }
        let sep = if line + word.len() > 76 { b'\n' } else { b' ' };
        word.push(sep);
        line = if sep == b'\n' { 0 } else { line + word.len() };
        let n = word.len().min(CORPUS_SIZE - written);
        out.write_all(&word[..n])?;
        written += n;
    }
    Ok(())
}
fn embed(input: impl Read, out: &mut impl Write, name: &str) -> io::Result<bool> {
    write!(out, "static const unsigned char {name}[] = {{")?;
    let mut n = 0;
    for b in io::BufReader::new(input).bytes() {
        if n % 24 == 0 {
            writeln!(out)?;
        }
        write!(out, "{},", b?)?;
        n += 1;
    }
    writeln!(out, "\n}};")?;
    Ok(n != 0)
}
fn run(args: &[String], input: impl Read, out: &mut impl Write) -> io::Result<i32> {
    match args {
        [mode] if mode == "text" => {
            text(out)?;
            Ok(0)
        }
        [mode] if mode == "header" => {
            writeln!(
                out,
                "/* generated by src/bench/corpus.rs: LordBench's xz workload input */"
            )?;
            writeln!(out, "#define LB_CORPUS_SIZE {CORPUS_SIZE}u")?;
            Ok(if embed(input, out, "lb_corpus_xz")? {
                0
            } else {
                1
            })
        }
        [mode, name]
            if mode == "embed"
                && name
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_') =>
        {
            Ok(if embed(input, out, name)? { 0 } else { 1 })
        }
        _ => Ok(2),
    }
}
fn main() -> std::process::ExitCode {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let mut out = io::BufWriter::new(io::stdout().lock());
    match run(&args, io::stdin().lock(), &mut out).and_then(|rc| {
        out.flush()?;
        Ok(rc)
    }) {
        Ok(2) => {
            eprintln!("usage: lbcorpus text | header < corpus.xz | embed <name> < file");
            std::process::ExitCode::from(2)
        }
        Ok(rc) => std::process::ExitCode::from(rc as u8),
        Err(e) => {
            eprintln!("lbcorpus: {e}");
            std::process::ExitCode::FAILURE
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn corpus_is_the_pinned_two_megabyte_input() {
        let mut data = Vec::new();
        text(&mut data).unwrap();
        assert_eq!(data.len(), CORPUS_SIZE);
        // Golden fingerprint of the former C generator, measured before removal.
        let fingerprint = data.iter().fold(14695981039346656037u64, |h, b| {
            (h ^ *b as u64).wrapping_mul(1099511628211)
        });
        assert_eq!(fingerprint, 0x665481da2483de08);
    }
    #[test]
    fn headers_preserve_byte_order_and_reject_invalid_identifiers() {
        let mut out = Vec::new();
        assert_eq!(
            run(
                &["embed".into(), "font".into()],
                &b"\0\x7f\xff"[..],
                &mut out
            )
            .unwrap(),
            0
        );
        assert_eq!(
            out,
            b"static const unsigned char font[] = {\n0,127,255,\n};\n"
        );
        assert_eq!(
            run(
                &["embed".into(), "../font".into()],
                &b"x"[..],
                &mut Vec::new()
            )
            .unwrap(),
            2
        );
        assert_eq!(
            run(&["header".into()], &b""[..], &mut Vec::new()).unwrap(),
            1
        );
    }
}
